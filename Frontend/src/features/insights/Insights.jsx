import { useState } from 'react'

import { Link }     from 'react-router-dom'

import { useDocTitle } from '../../hooks/useDocTitle.js'

import { getAllSignals } from '../../mocks/aiSignals.js'

import { STOCKS }       from '../../mocks/stocks.js'

import { SIGNAL_COLORS } from '../../utils/constants.js'

import Badge     from '../../components/ui/Badge.jsx'

import PriceChange from '../../components/ui/PriceChange.jsx'



const DISCLAIMER = `These signals are generated by an educational machine learning model that combines technical indicators (SMA, EMA, RSI, MACD) with FinBERT news sentiment scores. The model outputs a probability distribution across BUY, HOLD, and SELL classes.\n\nImportant limitations:\n* Past performance does not guarantee future results.\n* The model does not account for fundamental analysis, company financials, or macroeconomic factors.\n* This is a final-year engineering project for educational purposes only.\n* No accuracy or profit claims are made. Do not use these signals for real investment decisions.\n* Always consult a SEBI-registered financial advisor before investing.`



export default function Insights() {

  useDocTitle('AI Insights')

  const [filter,  setFilter]  = useState('ALL')

  const [sortBy,  setSortBy]  = useState('confidence')

  const [showInfo, setShowInfo] = useState(false)



  let signals = getAllSignals()

  if (filter !== 'ALL') signals = signals.filter(s => s.signal === filter)

  signals = [...signals].sort((a, b) => sortBy === 'confidence' ? b.confidence - a.confidence : a.symbol.localeCompare(b.symbol))



  return (

    <div style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem' }}>

      <div className="page-header">

        <div>

          <h1 className="page-header__title">AI Insights</h1>

          <p className="page-header__sub">Educational signals combining technical indicators and news sentiment</p>

        </div>

      </div>



      {/* Disclaimer banner */}

      <div style={{ background: 'var(--down-bg)', border: '1px solid rgba(244,63,94,.25)', borderRadius: 'var(--r)', padding: '.75rem 1rem', fontSize: '.78rem', color: 'var(--down)', lineHeight: 1.5 }}>

        ! <strong>Educational signals only.</strong> These are not investment recommendations. No accuracy or profit claims are made. Not a substitute for professional financial advice. No real orders are placed.

      </div>



      {/* Filters */}

      <div style={{ display: 'flex', gap: '.65rem', flexWrap: 'wrap', alignItems: 'center' }}>

        <div style={{ display: 'flex', gap: 4 }}>

          {['ALL','BUY','HOLD','SELL'].map(f => (

            <button key={f} onClick={() => setFilter(f)}

              style={{

                padding: '.28rem .7rem', border: 'none', borderRadius: 20, fontSize: '.75rem', fontWeight: 600, cursor: 'pointer',

                background: filter === f ? SIGNAL_COLORS[f === 'ALL' ? 'HOLD' : f]?.bg ?? 'var(--accent-bg)' : 'var(--card-hi)',

                color: filter === f ? SIGNAL_COLORS[f === 'ALL' ? 'HOLD' : f]?.color ?? 'var(--accent)' : 'var(--tx-3)',

              }}

            >{f}</button>

          ))}

        </div>

        <select

          value={sortBy} onChange={e => setSortBy(e.target.value)}

          style={{ background: 'var(--card-hi)', border: '1px solid var(--border)', borderRadius: 'var(--r)', padding: '.35rem .65rem', color: 'var(--tx)', fontSize: '.78rem', cursor: 'pointer' }}

        >

          <option value="confidence">Sort: Confidence </option>

          <option value="symbol">Sort: Symbol A-Z</option>

        </select>

        <button

          onClick={() => setShowInfo(v => !v)}

          style={{ marginLeft: 'auto', background: 'none', border: '1px solid var(--border)', borderRadius: 'var(--r)', padding: '.3rem .7rem', fontSize: '.72rem', color: 'var(--tx-3)', cursor: 'pointer' }}

        >

          {showInfo ? '^ Hide' : 'v Show'} model transparency

        </button>

      </div>



      {/* Model transparency accordion */}

      {showInfo && (

        <div className="card" style={{ border: '1px solid var(--accent-ring)' }}>

          <div style={{ fontSize: '.88rem', fontWeight: 700, color: 'var(--tx)', marginBottom: '.75rem' }}>Model Transparency</div>

          <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '1rem' }}>

            {[

              { title: 'Inputs', body: 'SMA (20, 50), EMA (12, 26), RSI (14), MACD (12,26,9) computed from historical OHLCV data. FinBERT sentiment score (mean of recent news).' },

              { title: 'Output', body: 'A 3-class probability distribution: P(BUY), P(HOLD), P(SELL). The class with highest probability is the signal. Confidence = that probability.' },

              { title: 'Limitations', body: 'No fundamental analysis. No live data in demo mode. Past signals may not reflect live model performance. Very short history windows reduce accuracy.' },

              { title: 'Disclaimer', body: 'For a B.E. IT academic project only. Not validated for real trading. The university and authors accept no responsibility for financial decisions based on these signals.' },

            ].map(item => (

              <div key={item.title} style={{ background: 'var(--card-hi)', borderRadius: 'var(--r)', padding: '.85rem' }}>

                <div style={{ fontSize: '.75rem', fontWeight: 700, color: 'var(--tx)', marginBottom: 5 }}>{item.title}</div>

                <div style={{ fontSize: '.75rem', color: 'var(--tx-2)', lineHeight: 1.6 }}>{item.body}</div>

              </div>

            ))}

          </div>

        </div>

      )}



      {/* Signal cards grid */}

      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(280px, 1fr))', gap: '1rem' }}>

        {signals.map(sig => {

          const stock  = STOCKS.find(s => s.symbol === sig.symbol)

          const colors = SIGNAL_COLORS[sig.signal]

          return (

            <Link key={sig.symbol} to={`/app/stocks/${sig.symbol}`}

              style={{ textDecoration: 'none' }}

            >

              <div className="card card--hover" style={{ borderColor: colors.border, display: 'flex', flexDirection: 'column', gap: '0.75rem', height: '100%' }}>

                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>

                  <div>

                    <div style={{ fontWeight: 700, fontSize: '1rem', color: 'var(--tx)', fontFamily: 'var(--mono)' }}>{sig.symbol}</div>

                    <div style={{ fontSize: '.7rem', color: 'var(--tx-3)' }}>{stock?.sector}</div>

                  </div>

                  <Badge label={sig.signal} preset={sig.signal} size="md" />

                </div>



                {/* Confidence ring */}

                <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem' }}>

                  <svg width={48} height={48} viewBox="0 0 48 48" aria-label={`Confidence: ${Math.round(sig.confidence * 100)}%`}>

                    <circle cx="24" cy="24" r="19" fill="none" stroke="var(--border)" strokeWidth="4" />

                    <circle cx="24" cy="24" r="19" fill="none"

                      stroke={colors.color} strokeWidth="4" strokeLinecap="round"

                      strokeDasharray={`${sig.confidence * 119.38} 119.38`}

                      transform="rotate(-90 24 24)"

                      style={{ transition: 'stroke-dasharray .4s' }}

                    />

                    <text x="24" y="28" textAnchor="middle" fontSize="10" fontWeight="700" fill={colors.color} fontFamily="var(--mono)">

                      {Math.round(sig.confidence * 100)}%

                    </text>

                  </svg>

                  <div style={{ flex: 1 }}>

                    {[['BUY', sig.buy, '#10B981'],['HOLD', sig.hold, '#F59E0B'],['SELL', sig.sell, '#F43F5E']].map(([lbl, val, clr]) => (

                      <div key={lbl} style={{ display: 'flex', alignItems: 'center', gap: 5, marginBottom: 3 }}>

                        <span style={{ fontSize: '.6rem', color: 'var(--tx-3)', width: 24 }}>{lbl}</span>

                        <div style={{ flex: 1, height: 4, background: 'var(--border)', borderRadius: 2 }}>

                          <div style={{ height: '100%', width: `${val * 100}%`, background: clr, borderRadius: 2 }} />

                        </div>

                        <span style={{ fontSize: '.6rem', fontFamily: 'var(--mono)', color: 'var(--tx-3)', width: 28, textAlign: 'right' }}>{Math.round(val * 100)}%</span>

                      </div>

                    ))}

                  </div>

                </div>



                <div style={{ fontSize: '.72rem', color: 'var(--tx-2)', lineHeight: 1.5, flex: 1 }}>

                  {sig.reasoning.slice(0, 90)}...

                </div>

              </div>

            </Link>

          )

        })}

      </div>

    </div>

  )

}

